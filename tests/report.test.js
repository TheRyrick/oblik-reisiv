/*
 * Автотести розбору тексту з Телеграму (js/report.js). Запуск: npm test
 */
'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const R = require('../js/report.js');

const pay = (r) => r.payments.map((p) => `${p.amount}:${p.method}:${p.received ? '+' : '?'}`);

test('заявка: лише рядки з грн; розміри, телефони, адреси — не гроші', () => {
  const r = R.parse(`Днепр - Хмельницкий
400кг (1.23/1.66/2.27м - 1шт )
7000грн / на карту
6000грн / в день выгрузки
1000грн / по оригиналам
0962492673 Леся

м. Дніпро, вул. Данила Галицького, 1Д
+38 067 230 77 78 Сергей
груз для конкород груп`);
  assert.equal(r.route, 'Днепр → Хмельницкий');
  assert.equal(r.startDate, '', 'розміри 1.23/1.66 — не дата');
  assert.deepEqual(pay(r), ['7000:card:+', '6000:bank:?', '1000:bank:?']);
  assert.equal(r.payments[1].guessed, true, 'спосіб не вказано — позначено');
  assert.equal(r.payments[2].guessed, true, '«оригиналам» — не готівка');
  assert.equal(r.cash, 0);
  assert.equal(r.card + r.bank, 14000);
  assert.equal(r.customer, 'конкород груп');
});

test('заявка: наличка на вигрузці, документи з датами — не дата рейсу', () => {
  const r = R.parse(`Дніпро - Іллінці - Вінниця - Поляниця (И.Франковск)
880кг 6.4куба (коробки)
16000грн / наличка на выгрузке

Загрузка: Дніпро , Сонячна набережна 96   з 9-00 до 18-00   +380677115964 Олексій             https://www.google.com/maps/place/48.468913,35.094586/@48.468913,35.094586,18z
Реализация товаров и услуг УТ000027726 от 28.10.2026 9:32:05
Андрій 0665699659`);
  assert.equal(r.route, 'Дніпро → Іллінці → Вінниця → Поляниця (И.Франковск)');
  assert.equal(r.startDate, '');
  assert.deepEqual(pay(r), ['16000:cash:+']);
});

test('заявка: ФОП і номер заявки не стають безналом', () => {
  const r = R.parse(`Днепр - Черкассы
300кг 2 куба (коробки)
2500грн / наличка на выгрузке
+380684506826 Евгений
Загрузка: пр. Богдана Хмельницького 160 м. Дніпро
з  8 до 16 обід з 12 до 13
Замовлення ФОП Бабаенко (заявка 710/1)`);
  assert.deepEqual(pay(r), ['2500:cash:+']);
  assert.equal(r.bank, 0);
  assert.equal(r.customer, 'ФОП Бабаенко');
});

test('заявка: «3ю группу» не додається до суми, безнал — чекаємо', () => {
  const r = R.parse(`На завтра на самое утро:

Черкассы - Житомир
1.5т 10 евро паллет
12500грн / безнал на 3ю группу без пдв
0951601479 Олександр`);
  assert.equal(r.route, 'Черкассы → Житомир');
  assert.deepEqual(pay(r), ['12500:bank:?']);
  assert.equal(r.customer, 'Олександр 0951601479');
});

test('звіт за рейс: діапазон дат, 19 замовлень, диспетчерські, касса', () => {
  const r = R.parse(`27.10–06.11.2026

Днепр - Винница - Шептицький - Львов - Одесса - Херсон - Одесса-Бердичев-Кривой-Рог

1) 13000грн / безнал
2) 4300грн / карта
3) 8000грн / безнал
4) 8000грн / наличка
5) 3000грн / карта
6) 25000грн / наличка
7) 9000грн / безнал
8) 8000грн / наличка
9) 3000грн / наличка
10) 5250грн/ безнал
11) 3000грн/ на карту
12) 7000/наличка
13) 3200грн/наличка
14) 4000грн/карта
15) 7000грн/наличка
16) 4500грн/карта
17) 4500грн/карта
18) 4000грн/ наличка
-300гр/диспетчерских
3700грн/касса

18) 5000грн/безнал`);
  assert.equal(r.startDate, '2026-10-27');
  assert.equal(r.endDate, '2026-11-06');
  assert.equal(r.route, 'Днепр → Винница → Шептицький → Львов → Одесса → Херсон → Одесса → Бердичев → Кривой-Рог');
  assert.equal(r.payments.length, 19);
  assert.equal(r.bank, 13000 + 8000 + 9000 + 5250 + 5000);
  assert.equal(r.card, 4300 + 3000 + 3000 + 4000 + 4500 + 4500);
  assert.equal(r.cash, 8000 + 25000 + 8000 + 3000 + 7000 + 3200 + 7000 + 4000);
  assert.equal(r.dispatch, 300);
  assert.equal(r.payments[11].amount, 7000, '«7000/наличка» без «грн» — теж гроші');
  assert.equal(r.payments[0].order, 1);
  assert.equal(r.payments.filter((p) => !p.received).length, 5, 'безнал — чекаємо, решта — отримано');
  assert.equal(r.guessed, 0);
});

test('старі формати звіту працюють', () => {
  const r = R.parse(`28.10.2026
Днепр - Поляниця — Киев
1) 12000грн / безнал
2) 7000грн / наличка
-1000грн / диспетчерских
6000грн / касса
Диспетчерские: 500`);
  assert.equal(r.startDate, '2026-10-28');
  assert.equal(r.bank, 12000);
  assert.equal(r.cash, 7000);
  assert.equal(r.dispatch, 1500);
  const x = R.parse('12000 нал (1500 дисп)');
  assert.equal(x.cash, 12000);
  assert.equal(x.dispatch, 1500);
  const y = R.parse('4500 нал\n-1500 дисп\n3000 карта');
  assert.equal(y.cash, 4500);
  assert.equal(y.card, 0, '3000 — залишок після диспетчерських');
  assert.equal(R.parse('28.12–03.01.2027').startDate, '2026-12-28');
});
